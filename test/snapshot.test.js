'use strict';
const test = require('node:test');
const assert = require('node:assert/strict');
const { toSnapshot } = require('../scripts/sheet-to-snapshot');
const Core = require('../src/core.js');

const pad = (...c) => ['', '', '', ...c];
const sheets = [{
  name: 'Октябрь',
  rows: [
    pad('Отдел продаж', 'План', 'Реал. План', 'Факт', '', '01.10', '02.10', '03.10'),
    pad('План', '1 000 000₽', '500 000₽', '60 000₽'),
    pad('Деньги в кассе', '1 000 000₽', '500 000₽', '60 000₽', '', '0₽', '20 000₽', '40 000₽'),
    pad('Количество оплат', '10', '5', '2', '', '0', '1', '1'),
    pad('Новые заявки', '19', '10', '3', '', '0', '2', '1'),
    [],
    pad('Кристина', 'План', 'Реал. План', 'Факт', '', '01.10', '02.10', '03.10'),
    pad('План', '1 000 000₽', '500 000₽', '60 000₽'),
    pad('Количество оплат', '2', '1', '2', '', '0', '1', '1'),
    pad('Новые заявки', '10', '5', '3', '', '0', '2', '1'),
    pad('Деньги в кассе', '1 000 000₽', '500 000₽', '60 000₽', '', '0₽', '20 000₽', '40 000₽'),
  ],
}, {
  name: 'Сентябрь',
  rows: [
    pad('Отдел продаж', 'План', 'Факт', '', '01.09', '02.09'),
    pad('Деньги в кассе', '100 000₽', '30 000₽', '', '10 000₽', '20 000₽'),
    pad('Кристина', 'План', 'Факт', '', '01.09', '02.09'),
    pad('Деньги в кассе', '100 000₽', '30 000₽', '', '10 000₽', '20 000₽'),
  ],
}];

test('листы таблицы превращаются в выгрузку без разделителя колонок', () => {
  const t = toSnapshot(sheets);
  assert.ok(t.startsWith('# Октябрь\nОтдел продаж,План,Реал. План,Факт,01.10,02.10,03.10\n'));
  assert.ok(t.includes('# Сентябрь\nОтдел продаж,План,Факт,01.09,02.09\n'));
});

test('ядро дашборда разбирает выгрузку и считает кассу', () => {
  const months = Core.build(toSnapshot(sheets), new Date('2026-10-28'));
  assert.deepEqual(months.map((m) => m.name), ['Сентябрь', 'Октябрь']);
  const total = Core.aggregate(months).totals;
  assert.equal(total.cash, 60000 + 30000);
  assert.equal(total.pay, 2);
});
